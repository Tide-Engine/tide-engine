// Sampling copies preserve the original target; their private sRGB attachments encode
// linear premultiplied RGB. Public frag outputs and target readback are untouched.

static const char *const linear_texture_wgsl = WGSL(
    "struct Uniforms { layer: vec4i }\n"
    "@group(0) @binding(0) var<uniform> u: Uniforms;\n"
    "@group(0) @binding(2) var sampled: sampler;\n"
    "@vertex fn vertex(@builtin(vertex_index) i: u32) -> @builtin(position) vec4f {\n"
    "    let corner = vec2f(f32((i << 1u) & 2u), f32(i & 2u));\n"
    "    return vec4f(corner * 2.0 - 1.0, 0.0, 1.0);\n"
    "}\n"
    "fn linear_channel(v: f32) -> f32 {\n"
    "    let x = clamp(v, 0.0, 1.0);\n"
    "    if (x <= 0.04045) { return x / 12.92; }\n"
    "    return pow((x + 0.055) / 1.055, 2.4);\n"
    "}\n"
    "fn linear_color(c: vec4f) -> vec4f {\n"
    "    if (c.a <= 0.0) { return vec4f(0.0); }\n"
    "    let straight = c.rgb / c.a;\n"
    "    return vec4f(vec3f(linear_channel(straight.r), linear_channel(straight.g), linear_channel(straight.b)) * c.a, c.a);\n"
    "}\n"
    "@group(0) @binding(1) var image: texture_2d<f32>;\n"
    "@fragment fn fragment(@builtin(position) p: vec4f) -> @location(0) vec4f {\n"
    "    return linear_color(textureLoad(image, vec2i(p.xy), 0));\n"
    "}\n");

