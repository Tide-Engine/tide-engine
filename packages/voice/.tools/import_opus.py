"""Import pinned libopus without requiring package-specific compiler flags.

Usage: python packages/voice/.tools/import_opus.py <opus-1.6.1.tar.gz>
Only include paths and source suffixes change. Each selected translation unit
has a small C wrapper; vendor sources use .c.h so Tide's recursive C discovery
does not compile them twice. Header dependencies remain visible to its cache.
"""
import hashlib
import io
import os
from pathlib import Path, PurePosixPath
import re
import sys
import tarfile

raw = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(raw).hexdigest() == "6ffcb593207be92584df15b32466ed64bbec99109f007c82205f0194572411a1"
with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as archive:
    files = {m.name.removeprefix("opus-1.6.1/"): archive.extractfile(m).read()
             for m in archive.getmembers() if m.isfile()}
root = Path(__file__).resolve().parents[1]
include_dirs = [PurePosixPath(p) for p in ("include", "src", "celt", "silk", "silk/float", ".")]
selected = []
for filename, names in [("opus_sources.mk", ["OPUS_SOURCES", "OPUS_SOURCES_FLOAT"]),
                        ("celt_sources.mk", ["CELT_SOURCES"]),
                        ("silk_sources.mk", ["SILK_SOURCES", "SILK_SOURCES_FLOAT"])]:
    text = files[filename].decode().replace("\\\n", " ")
    for name in names:
        selected += re.search(r"^" + name + r"\s*=([^\n]+)", text, re.M)[1].split()
pending = list(selected)
copied = set()

def destination(name):
    return root / "opus" / (name + ".h" if name.endswith(".c") else name)

while pending:
    name = pending.pop()
    if name in copied:
        continue
    copied.add(name)
    path = destination(name)
    path.parent.mkdir(parents=True, exist_ok=True)
    def include(match):
        header = match[2]
        if header == "config.h":
            target = root / "opus/config.h"
        else:
            choices = [PurePosixPath(name).parent / header] + [p / header for p in include_dirs]
            found = next((str(p) for p in choices if str(p) in files), None)
            if found is None:
                return match[0]  # An unused platform-only include.
            pending.append(found)
            target = destination(found)
        return match[1] + '"' + os.path.relpath(target, path.parent).replace("\\", "/") + '"'
    data = re.sub(r'(^\s*#\s*include\s*)"([^"]+)"', include, files[name].decode(), flags=re.M)
    path.write_text(data, encoding="utf-8", newline="\n")

(root / "codec").mkdir(exist_ok=True)
for name in selected:
    (root / "codec" / name.replace("/", "_")).write_text(
        '// libopus 1.6.1; generated by .tools/import_opus.py.\n'
        '#include "../opus/config.h"\n#include "../opus/' + name + '.h"\n',
        encoding="utf-8", newline="\n")
for name in ["COPYING", "AUTHORS"]:
    (root / "opus" / name).write_bytes(files[name])
(root / "opus/config.h").write_text('''#pragma once
// Portable floating-point Opus; no CPU dispatch, neural models or extensions.
#define HAVE_CONFIG_H 1
#define OPUS_BUILD 1
#define VAR_ARRAYS 1
#define HAVE_LRINT 1
#define HAVE_LRINTF 1
#define HAVE_STDINT_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define PACKAGE_VERSION "1.6.1"
''', encoding="utf-8", newline="\n")
print(f"Imported {len(selected)} translation units and {len(copied)} source/header files.")
