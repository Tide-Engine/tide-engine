"""Import pinned RNNoise 0.2 and its upstream little model into this package.

Usage: python packages/voice/import_rnnoise.py <v0.2.tar.gz> <model.tar.gz>
Only quoted include paths/source suffixes change. No network access is needed.
"""
import hashlib
import pathlib
import posixpath
import re
import sys
import tarfile

PINS = (
    "e4a17eb1493b7551f9f7781d2acc67b8847d6ed7c4b64db0fd62c017021ae1ec",
    "4ac81c5c0884ec4bd5907026aaae16209b7b76cd9d7f71af582094a2f98f4b43",
)
SOURCES = "denoise rnn pitch kiss_fft celt_lpc nnet nnet_default parse_lpcnet_weights rnnoise_data rnnoise_tables".split()


def archive(path, pin):
    data = pathlib.Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != pin:
        raise SystemExit(f"SHA-256 mismatch: {path}")
    with tarfile.open(path) as tar:
        return {m.name.removeprefix("rnnoise-0.2/"): tar.extractfile(m).read().decode()
                for m in tar.getmembers() if m.isfile()
                and (m.name.endswith((".c", ".h", "/COPYING", "/AUTHORS"))
                     or m.name in ("COPYING", "AUTHORS"))}


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    files = archive(sys.argv[1], PINS[0])
    model = archive(sys.argv[2], PINS[1])
    files["src/rnnoise_data.c"] = model["src/rnnoise_data_little.c"]
    files["src/rnnoise_data.h"] = model["src/rnnoise_data_little.h"]
    selected = {p for p in files if p.startswith(("src/", "include/")) and p.endswith(".h")}
    selected.update(f"src/{name}.c" for name in SOURCES)
    selected.update(("COPYING", "AUTHORS"))
    root = pathlib.Path(__file__).resolve().parent
    vendor = root / "rnnoise"
    wrappers = root / "denoise"
    wrappers.mkdir(exist_ok=True)

    def include(match, source):
        name = match[1]
        for candidate in (posixpath.normpath(posixpath.join(posixpath.dirname(source), name)),
                          "src/" + name, "include/" + name, name):
            if candidate in selected or candidate == "config.h":
                suffix = ".h" if candidate.endswith(".c") else ""
                relative = posixpath.relpath(candidate + suffix, posixpath.dirname(source))
                return f'#include "{relative}"'
        return match[0]

    for source in sorted(selected):
        dest = vendor / (source + (".h" if source.endswith(".c") else ""))
        dest.parent.mkdir(parents=True, exist_ok=True)
        content = re.sub(r'#\s*include\s+"([^"]+)"', lambda m: include(m, source), files[source])
        dest.write_text(content, newline="\n")
    for name in SOURCES:
        (wrappers / f"{name}.c").write_text(
            '// RNNoise 0.2; generated by ../import_rnnoise.py.\n'
            '#include "../rnnoise/config.h"\n'
            f'#include "../rnnoise/src/{name}.c.h"\n', newline="\n")


if __name__ == "__main__":
    main()
