#!/usr/bin/env python3
"""Offline ONNX Runtime oracle; generate/check standalone C inference fixtures.

Run with Python -B. Requires numpy, onnx and onnxruntime only when authoring.
Optional --library compares an independently compiled inference DLL/shared
library against ORT on another 1024 observations. Never runs during gameplay.
"""
import argparse
import ctypes
import hashlib
import importlib.util
import os
from pathlib import Path
import subprocess
import tempfile

import numpy as np
import onnxruntime as ort

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("microduck_policy_export", ROOT / "tools" / "export_policy.py")
export = importlib.util.module_from_spec(spec)
spec.loader.exec_module(export)
HEADER = Path(__file__).with_name("policy_expected.h")


def random_observations(count, seed):
    """Explicit xorshift32 + dyadic values; no NumPy generator/version coupling."""
    state = seed
    result = np.empty((count, 61), dtype=np.float32)
    gravity = [(0, 0, -1), (.6, 0, -.8), (0, -.8, -.6), (0, 0, 1), (-1, 0, 0)]
    for row in range(count):
        for column in range(61):
            state ^= (state << 13) & 0xffffffff
            state ^= state >> 17
            state ^= (state << 5) & 0xffffffff
            result[row, column] = ((state >> 8) % 4097 - 2048) / 2048
        result[row, :3] *= 4
        result[row, 3:6] = gravity[row % len(gravity)]
        result[row, 6:20] *= .5
        result[row, 20:34] *= 8
        result[row, 34:48] *= 2
        result[row, 48:61] *= .25
    return result


def fixtures():
    zero = np.zeros(61, dtype=np.float32)
    standing = zero.copy()
    standing[5] = -1
    pitch = standing.copy()
    pitch[3:6] = [.6, 0, -.8]
    roll = standing.copy()
    roll[3:6] = [0, -.8, -.6]
    inverted = standing.copy()
    inverted[5] = 1
    prior = standing.copy()
    prior[34:48] = np.arange(-7, 7, dtype=np.float32) / 8
    commanded = standing.copy()
    commanded[48:61] = [.3, -.1, .4, -.2, .1, .3, -.1, 0, 0, -.02, .15, -.1, 0]
    moving = pitch.copy()
    moving[:3] = [1, -2, .5]
    moving[6:20] = np.arange(-7, 7, dtype=np.float32) / 32
    moving[20:34] = np.arange(7, -7, -1, dtype=np.float32) / 2
    subnormal = standing.copy()
    subnormal[0] = np.float32(float.fromhex("0x1p-149"))
    subnormal[1] = -subnormal[0]
    names = ["zero", "standing", "pitch", "roll", "inverted", "prior_action", "commanded", "moving", "subnormal"]
    inputs = np.vstack([zero, standing, pitch, roll, inverted, prior, commanded, moving, subnormal,
                        random_observations(64, 0x4d445038)])
    names += [f"random_{i:02d}" for i in range(64)]
    return names, inputs


def session():
    export.load_verified_model()
    options = ort.SessionOptions()
    options.intra_op_num_threads = 1
    options.inter_op_num_threads = 1
    options.execution_mode = ort.ExecutionMode.ORT_SEQUENTIAL
    # Disable graph fusion: evaluate the released graph directly.
    options.graph_optimization_level = ort.GraphOptimizationLevel.ORT_DISABLE_ALL
    return ort.InferenceSession(str(export.MODEL), options, providers=["CPUExecutionProvider"])


def evaluate(model, inputs):
    return np.vstack([model.run(["actions"], {"obs": row[None, :]})[0][0] for row in inputs])


def header_bytes(names, inputs, expected):
    lines = ["/* Generated by test/policy_oracle.py using independent ONNX Runtime CPU.",
             f" * ONNX SHA-256 {export.MODEL_SHA256}",
             " * Fixed standing/tilted/prior-action/command/fall and xorshift fixtures.",
             " * Expected values are ORT outputs, never outputs from the C runtime.",
             " */", "#ifndef MICRODUCK_POLICY_EXPECTED_H", "#define MICRODUCK_POLICY_EXPECTED_H", "",
             f"enum {{ MD_POLICY_FIXTURE_COUNT = {len(names)} }};",
             "static const char *const md_policy_fixture_names[MD_POLICY_FIXTURE_COUNT] = {",
             "    " + ", ".join(f'\"{name}\"' for name in names), "};", ""]
    for name, values, count in [("md_policy_fixture_observations", inputs, 61),
                                ("md_policy_fixture_expected", expected, 14)]:
        lines.append(f"static const float {name}[MD_POLICY_FIXTURE_COUNT][{count}] = {{")
        for row in values:
            lines.append("    {" + ", ".join(export.float_literal(v) for v in row) + "},")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines).encode("ascii")


def compare_library(path, model):
    library = ctypes.CDLL(str(path.resolve()))
    function = library.md_policy_evaluate
    pointer = ctypes.POINTER(ctypes.c_float)
    function.argtypes = [pointer, pointer]
    function.restype = ctypes.c_int
    _, fixed = fixtures()
    inputs = np.vstack([fixed, random_observations(1024, 0x01c0ffee)])
    expected = evaluate(model, inputs)
    actual = np.empty_like(expected)
    for row, output in zip(inputs, actual):
        if function(row.ctypes.data_as(pointer), output.ctypes.data_as(pointer)) != 1:
            raise ValueError("C runtime unexpectedly rejected a finite fixture")
    difference = np.abs(actual - expected)
    tolerance = .0002 + .00002 * np.abs(expected)
    if not np.isfinite(actual).all() or not (difference <= tolerance).all():
        raise ValueError(f"ORT comparison failed: max absolute error {difference.max()}")
    print(f"ORT vs C: {len(inputs)} observations, max absolute error {difference.max():.9g}, "
          f"max tolerance fraction {(difference / tolerance).max():.9g}")


def compare_targets(native, wasm, node):
    """Run identical standalone C tests and compare every emitted action bit."""
    runner = """import { WASI } from 'node:wasi';
import { readFile } from 'node:fs/promises';
const wasi = new WASI({version:'preview1', args:['policy_runtime_test','--dump','actions.bin'],
  env:{TIDE_HIDDEN:'1'}, preopens:{'.':process.cwd()}});
const {instance} = await WebAssembly.instantiate(await readFile(process.argv[2]), wasi.getImportObject());
wasi.start(instance);
"""
    env = dict(os.environ, TIDE_HIDDEN="1")
    with tempfile.TemporaryDirectory(prefix="microduck-policy-") as temporary:
        scratch = Path(temporary)
        javascript = scratch / "run-wasi.mjs"
        javascript.write_text(runner, encoding="ascii")
        native_result = subprocess.run([str(native.resolve()), "--dump", str(scratch / "native.bin")],
                                       cwd=scratch, env=env, capture_output=True, text=True, check=True)
        wasi_result = subprocess.run([node, str(javascript), str(wasm.resolve())], cwd=scratch,
                                     env=env, capture_output=True, text=True, check=True)
        a, b = (scratch / "native.bin").read_bytes(), (scratch / "actions.bin").read_bytes()
        if a != b or len(a) != (len(fixtures()[0]) + 512) * 14 * 4:
            raise ValueError("native/WASI full action streams differ or have the wrong length")
        print("native: " + native_result.stdout.strip())
        print("WASI:   " + wasi_result.stdout.strip())
        print(f"native/WASI identical: {len(a)} bytes; SHA-256 {hashlib.sha256(a).hexdigest()}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--library", type=Path)
    parser.add_argument("--native-executable", type=Path)
    parser.add_argument("--wasi-module", type=Path)
    parser.add_argument("--node", default="node", help="Node executable with node:wasi support")
    args = parser.parse_args()
    if bool(args.native_executable) != bool(args.wasi_module):
        parser.error("--native-executable and --wasi-module must be supplied together")
    model = session()
    names, inputs = fixtures()
    data = header_bytes(names, inputs, evaluate(model, inputs))
    if args.check:
        if HEADER.read_bytes() != data:
            raise ValueError("policy_expected.h is stale; regenerate with policy_oracle.py")
    else:
        HEADER.write_bytes(data)
    print(f"{'verified' if args.check else 'wrote'} {len(names)} ORT fixtures; "
          f"onnxruntime {ort.__version__}, numpy {np.__version__}")
    if args.library:
        compare_library(args.library, model)
    if args.native_executable:
        compare_targets(args.native_executable, args.wasi_module, args.node)


if __name__ == "__main__":
    main()
