#!/usr/bin/env python3
"""Authoring-only, lossless export of the pinned released VelStand ONNX tensors.

Requires numpy and onnx. No ONNX tooling is used by the C runtime. An unknown
model, graph, tensor type, shape, attribute, or connection is an error.
"""
import argparse
import hashlib
from pathlib import Path

import numpy as np
import onnx
from onnx import numpy_helper

MODEL_SHA256 = "2fc7f8ee6acd7d0d3f66a99927b5d5a56589aeed02ec714de329b252d5ccf492"
MODEL_SIZE = 793705
ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "policy" / "velstand.onnx"
HEADER = ROOT / "policy" / "model_weights.h"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def load_verified_model(path=MODEL):
    data = Path(path).read_bytes()
    require(len(data) == MODEL_SIZE, "not the pinned model: byte count differs")
    require(hashlib.sha256(data).hexdigest() == MODEL_SHA256,
            "not the pinned model: SHA-256 differs")
    model = onnx.load_model_from_string(data)
    onnx.checker.check_model(model, full_check=True)
    require(model.ir_version == 8 and [(x.domain, x.version) for x in model.opset_import] == [("", 18)],
            "unsupported IR/opset")
    graph = model.graph
    require(not model.functions and not graph.sparse_initializer, "unsupported functions/sparse tensors")
    for values, name, size in [(graph.input, "obs", 61), (graph.output, "actions", 14)]:
        require(len(values) == 1 and values[0].name == name, "unsupported graph interface")
        tensor = values[0].type.tensor_type
        require(tensor.elem_type == onnx.TensorProto.FLOAT and
                [d.dim_value for d in tensor.shape.dim] == [1, size] and
                not any(d.dim_param for d in tensor.shape.dim), "unsupported interface type/shape")
    specs = [("obs_normalizer._mean", (1, 61), "md_policy_mean"),
             ("onnx::Div_24", (1, 61), "md_policy_divisor")]
    widths = [61, 512, 256, 128, 14]
    for layer in range(4):
        specs += [(f"mlp.{2 * layer}.weight", (widths[layer + 1], widths[layer]),
                   f"md_policy_weight_{layer}"),
                  (f"mlp.{2 * layer}.bias", (widths[layer + 1],), f"md_policy_bias_{layer}")]
    initializers = {t.name: t for t in graph.initializer}
    require(len(initializers) == len(graph.initializer) == len(specs) and
            set(initializers) == {s[0] for s in specs}, "unsupported initializer set")
    arrays = []
    for name, shape, cname in specs:
        tensor = initializers[name]
        require(tensor.data_type == onnx.TensorProto.FLOAT and tuple(tensor.dims) == shape and
                tensor.data_location == onnx.TensorProto.DEFAULT and not tensor.external_data,
                f"unsupported tensor: {name}")
        array = numpy_helper.to_array(tensor)
        require(np.isfinite(array).all(), f"nonfinite tensor: {name}")
        if cname == "md_policy_divisor":
            require((array > 0).all(), "invalid normalization divisor")
        arrays.append((cname, array))
    # Exact dataflow, not just an allowlist of operator names.
    expected = [
        ("Sub", ["obs", "obs_normalizer._mean"], ["/obs_normalizer/Sub_output_0"], {}),
        ("Div", ["/obs_normalizer/Sub_output_0", "onnx::Div_24"],
         ["/obs_normalizer/Div_output_0"], {})]
    previous = "/obs_normalizer/Div_output_0"
    for layer in range(4):
        result = "actions" if layer == 3 else f"/mlp/mlp.{layer * 2}/Gemm_output_0"
        expected.append(("Gemm", [previous, f"mlp.{layer * 2}.weight", f"mlp.{layer * 2}.bias"],
                         [result], {"alpha": 1.0, "beta": 1.0, "transB": 1}))
        if layer != 3:
            suffix = "" if layer == 0 else f"_{layer}"
            previous = f"/mlp/mlp.1{suffix}/Elu_output_0"
            expected.append(("Elu", [result], [previous], {"alpha": 1.0}))
    require(len(graph.node) == len(expected), "unsupported node count")
    for node, (op, inputs, outputs, attrs) in zip(graph.node, expected):
        actual = {a.name: onnx.helper.get_attribute_value(a) for a in node.attribute}
        require(not node.domain and node.op_type == op and list(node.input) == inputs and
                list(node.output) == outputs and len(actual) == len(node.attribute) and actual == attrs,
                f"unsupported graph node: {node.name}")
    return model, arrays


def float_literal(value):
    # Exact float32 -> hexadecimal C literal; independent of locale/decimal IO.
    mantissa, exponent = float(value).hex().split("p")
    if "." in mantissa:
        mantissa = mantissa.rstrip("0").rstrip(".")
    return f"{mantissa}p{exponent}f"


def generated_header(arrays):
    lines = ["/* Generated by tools/export_policy.py; DO NOT EDIT.",
             " * Released Pollen Robotics VelStand v8; Apache-2.0 (see LICENSE).",
             f" * Source ONNX SHA-256: {MODEL_SHA256}",
             " * Original tensor bits and [output,input] weight order preserved.",
             " */", "#ifndef MICRODUCK_POLICY_MODEL_WEIGHTS_H",
             "#define MICRODUCK_POLICY_MODEL_WEIGHTS_H", ""]
    for name, array in arrays:
        flat = array.ravel(order="C")
        lines.append(f"static const float {name}[{len(flat)}] = {{")
        for start in range(0, len(flat), 6):
            lines.append("    " + ", ".join(float_literal(v) for v in flat[start:start + 6]) + ",")
        lines += ["};", ""]
    lines += ["#endif", ""]
    return "\n".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=MODEL)
    parser.add_argument("--output", type=Path, default=HEADER)
    parser.add_argument("--check", action="store_true", help="verify, without rewriting, the generated header")
    args = parser.parse_args()
    _, arrays = load_verified_model(args.model)
    data = generated_header(arrays)
    if args.check:
        require(args.output.read_bytes() == data, "generated header is stale; rerun export_policy.py")
    else:
        args.output.write_bytes(data)
    print(f"{'verified' if args.check else 'wrote'} {args.output.name}: "
          f"{sum(a.size for _, a in arrays)} float32 values; source SHA-256 {MODEL_SHA256}")


if __name__ == "__main__":
    main()
