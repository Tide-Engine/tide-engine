#!/usr/bin/env python3
"""Export frozen MicroDuck collision data; Python standard library only.

This is an asset exporter, not a mesh fitter. It reads no meshes and uses no
MuJoCo, NumPy, SciPy, network access, build tools, or shared caches.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import sys

EXPECTED_GEOMETRY_SHA256 = "72312ed6c599e568469135104d3fed438a9c1fe4f02f924dd954e748dc92b09d"
EXPECTED_SPHERES = 174
ROOT_KEYS = {"schema_version", "license", "coordinate_frame", "body_names", "sphere_count", "spheres"}
SPHERE_KEYS = {"body", "center", "radius", "foot"}


def finite_number(value, label):
    if type(value) not in (int, float) or not math.isfinite(value):
        raise ValueError(f"{label} must be a finite number")
    return float(value)


def validate_geometry(data):
    if not isinstance(data, dict) or set(data) != ROOT_KEYS:
        raise ValueError("Unexpected geometry document schema")
    if type(data["schema_version"]) is not int or data["schema_version"] != 1:
        raise ValueError("Unsupported schema_version")
    if data["license"] != "CC-BY-NC-SA-4.0":
        raise ValueError("Unexpected collision data license")
    if data["coordinate_frame"] != "original_mjcf_body_local_meters":
        raise ValueError("Expected original MJCF body-local coordinates in meters")
    names = data["body_names"]
    if not isinstance(names, list) or len(names) != 15 or any(not isinstance(n, str) or not n for n in names) or len(set(names)) != 15:
        raise ValueError("Expected 15 distinct body names")
    if type(data["sphere_count"]) is not int or data["sphere_count"] != EXPECTED_SPHERES:
        raise ValueError("Expected frozen 174-sphere model")
    spheres = data["spheres"]
    if not isinstance(spheres, list) or len(spheres) != EXPECTED_SPHERES:
        raise ValueError("Sphere count differs from frozen model")
    sole_counts = {0: 0, 1: 0}
    bodies = set()
    for index, sphere in enumerate(spheres):
        label = f"sphere[{index}]"
        if not isinstance(sphere, dict) or set(sphere) != SPHERE_KEYS:
            raise ValueError(f"{label} has unexpected fields")
        body, foot = sphere["body"], sphere["foot"]
        if type(body) is not int or not 0 <= body < 15:
            raise ValueError(f"{label}.body must be an integer in [0,14]")
        if type(foot) is not int or foot not in (-1, 0, 1):
            raise ValueError(f"{label}.foot must be -1,0,1")
        if foot >= 0 and body != (5 if foot == 0 else 14):
            raise ValueError(f"{label} has an inconsistent sole/body assignment")
        center = sphere["center"]
        if not isinstance(center, list) or len(center) != 3:
            raise ValueError(f"{label}.center must contain three numbers")
        for axis, value in enumerate(center):
            finite_number(value, f"{label}.center[{axis}]")
        if finite_number(sphere["radius"], f"{label}.radius") <= 0:
            raise ValueError(f"{label}.radius must be positive")
        bodies.add(body)
        if foot >= 0:
            sole_counts[foot] += 1
    if bodies != set(range(15)) or sole_counts != {0: 6, 1: 6}:
        raise ValueError("Frozen model must cover all bodies and retain six soles per foot")
    return spheres


def load_geometry(path):
    source = path.read_bytes()
    actual = hashlib.sha256(source).hexdigest()
    if actual != EXPECTED_GEOMETRY_SHA256:
        raise ValueError(f"Frozen JSON SHA-256 mismatch: {actual}")
    return validate_geometry(json.loads(source.decode("utf-8")))


def number(value):
    # 17 significant digits round-trip the frozen JSON's binary64 values.
    # The frozen numbers already preserve the tested nine-digit authoring
    # literals, including their float32 runtime conversions.
    result = format(float(value), ".17g")
    if "." not in result and "e" not in result.lower():
        result += ".0"
    return result


def render(spheres):
    lines = [
        "// Generated by tools/export_collisions.py; do not edit.",
        "// Derived collision data: Copyright Pollen Robotics, CC BY-NC-SA 4.0.",
        "// Source: https://github.com/pollen-robotics/microduck_rl",
        "// License: https://creativecommons.org/licenses/by-nc-sa/4.0/",
        "// Modified: 131 fitted support spheres,26 source-inscribed cores,16 original feet,1 procedural casing core.",
        "// Final casing core is an original procedural approximation; it is NOT source-inscribed and extends support.",
        "// See collision_provenance.json and LICENSE-COLLISIONS.md.",
        f"// Frozen JSON SHA-256: {EXPECTED_GEOMETRY_SHA256}",
        "// Coordinates are original MJCF body-local meters; principal conversion occurs at spawn.",
        "", "struct DuckCollisionDefinition", "{", "    int body;", "    float3 position;",
        "    float radius;", "    int foot = -1;", "}", "",
        "List<DuckCollisionDefinition> DuckCollisionModel()", "{", "    return [",
    ]
    for index, sphere in enumerate(spheres):
        center = ", ".join(number(v) for v in sphere["center"])
        suffix = "," if index + 1 < len(spheres) else ""
        lines.append("        DuckCollisionDefinition { "
                     f"body = {sphere['body']}, position = float3({center}), "
                     f"radius = {number(sphere['radius'])}, foot = {sphere['foot']}"
                     " }" + suffix)
    lines.extend(["    ];", "}", ""])
    return "\n".join(lines).encode("utf-8")


def main():
    package = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=package / "collision_spheres.json")
    parser.add_argument("--output", type=Path, default=package / "collisions.tide")
    parser.add_argument("--check", action="store_true", help="Check generated bytes without writing")
    args = parser.parse_args()
    try:
        expected = render(load_geometry(args.source))
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != expected:
                raise ValueError("collisions.tide differs; run tools/export_collisions.py")
        else:
            args.output.write_bytes(expected)
    except (ValueError, OSError, UnicodeError) as error:
        print(f"export_collisions: {error}", file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'exported'} {EXPECTED_SPHERES} frozen collision spheres")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
