"""Reproduce the benchmark's closed outward-wound architectural OBJ assets.

No imported content. Run with --check to compare bytes and check the topology.
The flat per-face normals keep arch edges crisp; the 24-sided column is faceted.
"""
import argparse
import math
from pathlib import Path


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def clean(point):
    return tuple(0.0 if abs(x) < 1e-12 else round(x, 9) for x in point)


class Mesh:
    def __init__(self, name):
        self.name = name
        self.faces = []

    def face(self, points, outward):
        points = list(map(clean, points))
        normal = cross(sub(points[1], points[0]), sub(points[2], points[0]))
        if dot(normal, outward) < 0:
            points.reverse()
        self.faces.append(points)

    def obj(self):
        # Check the actual rounded asset, not only the pre-serialization shape.
        edges = {}
        volume = 0.0
        for face in self.faces:
            for a, b in zip(face, face[1:] + face[:1]):
                key = tuple(sorted((a, b)))
                edges.setdefault(key, []).append((a, b))
            for i in range(1, len(face) - 1):
                a, b, c = face[0], face[i], face[i + 1]
                assert dot(cross(sub(b, a), sub(c, a)), cross(sub(b, a), sub(c, a))) > 1e-16
                volume += dot(a, cross(b, c)) / 6
        assert volume > 0
        assert all(len(pair) == 2 and pair[0] == pair[1][::-1] for pair in edges.values())
        lines = [f"# Authored {self.name}; generated by generate_meshes.py. Closed, outward wound."]
        vertex = 1
        for face_index, face in enumerate(self.faces, 1):
            normal = cross(sub(face[1], face[0]), sub(face[2], face[0]))
            length = math.sqrt(dot(normal, normal))
            normal = clean(tuple(x / length for x in normal))
            for point in face:
                lines.append("v " + " ".join(f"{x:.9f}" for x in point))
            lines.append("vn " + " ".join(f"{x:.9f}" for x in normal))
            lines.append("f " + " ".join(f"{vertex + i}//{face_index}" for i in range(len(face))))
            vertex += len(face)
        return ("\n".join(lines) + "\n").encode("ascii")


def cylinder():
    mesh = Mesh("24-sided unit-height column, radius 0.5")
    ring = [clean((math.cos(i * math.tau / 24) * 0.5, 0, math.sin(i * math.tau / 24) * 0.5)) for i in range(24)]
    for i, a in enumerate(ring):
        b = ring[(i + 1) % 24]
        mesh.face([(a[0], -0.5, a[2]), (b[0], -0.5, b[2]), (b[0], 0.5, b[2]), (a[0], 0.5, a[2])], (a[0] + b[0], 0, a[2] + b[2]))
        mesh.face([(0, -0.5, 0), (a[0], -0.5, a[2]), (b[0], -0.5, b[2])], (0, -1, 0))
        mesh.face([(0, 0.5, 0), (a[0], 0.5, a[2]), (b[0], 0.5, b[2])], (0, 1, 0))
    return mesh.obj()


def arch():
    mesh = Mesh("semicircular arch, outer radius 1, inner radius 0.82, depth 1")
    outer = [clean((math.cos(i * math.pi / 24), math.sin(i * math.pi / 24), 0)) for i in range(25)]
    inner = [clean((p[0] * 0.82, p[1] * 0.82, 0)) for p in outer]
    def at(point, z):
        return (point[0], point[1], z)
    for i in range(24):
        a, b, c, d = outer[i], outer[i + 1], inner[i + 1], inner[i]
        mesh.face([at(a, 0.5), at(b, 0.5), at(c, 0.5), at(d, 0.5)], (0, 0, 1))
        mesh.face([at(a, -0.5), at(b, -0.5), at(c, -0.5), at(d, -0.5)], (0, 0, -1))
        mesh.face([at(a, -0.5), at(b, -0.5), at(b, 0.5), at(a, 0.5)], (a[0] + b[0], a[1] + b[1], 0))
        mesh.face([at(c, -0.5), at(d, -0.5), at(d, 0.5), at(c, 0.5)], (-c[0] - d[0], -c[1] - d[1], 0))
    for i in (0, 24):
        mesh.face([at(outer[i], -0.5), at(inner[i], -0.5), at(inner[i], 0.5), at(outer[i], 0.5)], (0, -1, 0))
    return mesh.obj()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = Path(__file__).parent / "assets"
    if not args.check:
        directory.mkdir(exist_ok=True)
    for name, content in (("column.obj", cylinder()), ("arch.obj", arch())):
        path = directory / name
        if args.check:
            assert path.read_bytes() == content, f"{path} differs; rerun generator"
        else:
            path.write_bytes(content)
    print("Closed architectural meshes verified" if args.check else "Closed architectural meshes generated")


if __name__ == "__main__":
    main()
