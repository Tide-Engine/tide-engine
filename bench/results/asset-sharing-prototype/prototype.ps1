$env:TIDE_HIDDEN = '1'
$ErrorActionPreference = 'Stop'
# Scratch generated-code experiment. This does not implement general COW.
$taskRoot = (Get-Location).Path
$taskWork = Join-Path $taskRoot 'build/asset-reference-prototype'
New-Item -ItemType Directory -Force "$taskWork/base", "$taskWork/shared" | Out-Null
foreach ($taskVariant in @('base', 'shared')) {
    Copy-Item build/owned-animation/gen/game.c "$taskWork/$taskVariant/game.c"
    Copy-Item build/owned-animation/gen/game.h "$taskWork/$taskVariant/game.h"
}
$taskGame = [IO.File]::ReadAllText("$taskWork/shared/game.c").Replace("`r`n", "`n")
$taskChanges = @(
    @('    return tide_list_copy(l, sizeof(uint8_t));',
      '    return tide_pack_holds(l.at) ? l : tide_list_copy(l, sizeof(uint8_t));'),
    @('    tide_list_set(l, value, sizeof(uint8_t), where);',
      "    if (tide_pack_holds(value.at)) { tide_list_release(l, where); *l = value; }`n    else { if (tide_pack_holds(l->at)) l->at = 0; tide_list_set(l, value, sizeof(uint8_t), where); }"),
    @('    tide_list_own(l, sizeof(uint8_t), where);',
      '    if (!tide_pack_holds(l->at)) tide_list_own(l, sizeof(uint8_t), where);')
)
foreach ($taskChange in $taskChanges) {
    if ($taskGame.Split($taskChange[0], [StringSplitOptions]::None).Count -ne 2) {
        throw 'Generated byte-list helper differs from measured input'
    }
    $taskGame = $taskGame.Replace($taskChange[0], $taskChange[1])
}
[IO.File]::WriteAllText("$taskWork/shared/game.c", $taskGame, [Text.UTF8Encoding]::new($false))
foreach ($taskName in @('harness.c', 'containers.c', 'containers-simple.c', 'measure.ps1', 'measure-simple.ps1')) {
    Copy-Item "bench/results/asset-sharing-prototype/$taskName" "$taskWork/$taskName"
}
$taskClang = 'C:/Program Files/LLVM/bin/clang.exe'
$taskFlags = @('-std=c17', '-O2', '-D_DLL', '-D_MT', '-Xclang', '--dependent-lib=msvcrt',
    '-fno-fast-math', '-ffp-contract=off', '-I', 'engine/include')
foreach ($taskVariant in @('base', 'shared')) {
    & $taskClang @taskFlags -I "$taskWork/$taskVariant" "$taskWork/harness.c" build/owned-animation/gen/game_pack.c build/release/engine/tide.lib -lws2_32 -lbcrypt -o "$taskWork/grid-$taskVariant.exe"
    if ($LASTEXITCODE) { throw 'Grid compile failed' }
    $taskDefine = if ($taskVariant -eq 'shared') { '-DSHARED=1' } else { '-DSHARED=0' }
    foreach ($taskExperiment in @('', '-simple')) {
        & $taskClang @taskFlags -Wall -Wextra -Wpedantic -Werror $taskDefine "$taskWork/containers$taskExperiment.c" build/release/engine/tide.lib -lws2_32 -lbcrypt -o "$taskWork/containers$taskExperiment-$taskVariant.exe"
        if ($LASTEXITCODE) { throw 'Container compile failed' }
    }
}
