// Maintainer-only generator: npm ci --prefix docs, then node cmake/web_runtime.mjs --write.
// Normal builds verify the checked-in output without loading npm dependencies.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = 'platform/web/tide.release.js';
const manifestPath = 'platform/web/tide.release.json';
const version = '1.2.12';
const paths = ['platform/web/tide.js', 'platform/web/inflate.mjs', 'platform/third_party/fflate/browser.js',
    'platform/third_party/fflate/LICENSE', 'cmake/web_runtime.mjs', 'cmake/WebRuntime.cmake'];
const normalized = text => text.replace(/\r\n/g, '\n');
const digest = text => createHash('sha256').update(normalized(text)).digest('hex');
const inputs = {};
for (const path of paths) inputs[path] = digest(await readFile(resolve(root, path), 'utf8'));

if (process.argv[2] === '--check') {
    const manifest = JSON.parse(await readFile(resolve(root, manifestPath), 'utf8'));
    if (manifest.minifier !== `rolldown@${version}` || JSON.stringify(manifest.inputs) !== JSON.stringify(inputs)
        || digest(await readFile(resolve(root, output), 'utf8')) !== manifest.output) {
        throw new Error('Release web runtime is stale; npm ci --prefix docs && node cmake/web_runtime.mjs --write');
    }
    console.log('Release web runtime sources and generated output match.');
} else if (process.argv[2] === '--write') {
    const require = createRequire(resolve(root, 'docs/package.json'));
    const installed = JSON.parse(await readFile(require.resolve('rolldown/package.json'), 'utf8')).version;
    if (installed !== version) throw new Error(`Expected rolldown ${version}, found ${installed}; use docs npm ci`);
    const { rolldown } = await import(pathToFileURL(require.resolve('rolldown')));
    const { minifySync } = await import(pathToFileURL(require.resolve('rolldown/utils')));
    const bundle = await rolldown({ input: resolve(root, 'platform/web/inflate.mjs'), treeshake: { moduleSideEffects: false } });
    let inflate;
    try {
        const built = await bundle.generate({ format: 'iife', name: 'TideInflate' });
        inflate = built.output.find(item => item.type === 'chunk').code;
    } finally {
        await bundle.close();
    }
    const runtime = normalized(await readFile(resolve(root, 'platform/web/tide.js'), 'utf8'))
        .replace(/^[ \t]*\/\/ <tide run>\n[\s\S]*?^[ \t]*\/\/ <\/tide run>\n/gm, '');
    // Keep scope boundaries: threadMain is serialized into a Worker. Property
    // names are the browser/WASM/page ABI and must never be mangled.
    const options = { module: false, compress: false, mangle: { toplevel: false } };
    const made = minifySync('tide.release.js', `${inflate}\n${runtime}`, options);
    if (made.errors.length) throw new Error(JSON.stringify(made.errors));
    if (/<\/script/i.test(made.code)) throw new Error('Runtime contains an unescaped HTML script delimiter');
    const license = normalized(await readFile(resolve(root, 'platform/third_party/fflate/LICENSE'), 'utf8')).trim();
    const code = `// Generated by cmake/web_runtime.mjs; edit tide.js and regenerate.\n/*! fflate 0.8.3\n${license}\n*/\n${made.code}\n`;
    await writeFile(resolve(root, output), code);
    await writeFile(resolve(root, manifestPath), JSON.stringify({ minifier: `rolldown@${version}`,
        options, inputs, output: digest(code) }, null, 2) + '\n');
    console.log(`Release web runtime: ${Buffer.byteLength(code)} bytes.`);
} else {
    throw new Error('Use --check or --write');
}
