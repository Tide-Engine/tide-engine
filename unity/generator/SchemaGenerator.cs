using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Tide.Generator
{
    // C# types for a Tide game: one struct for each type of its schema (Packages/com.tide.game/schema.json, which
    // tide unity writes with each build that changes it), laid out as the game's C lays it out, so a view packet's
    // bytes read as them in place. Unity runs it for every assembly (its DLL is in no assembly's folder); it emits
    // into Tide.Game, that package's assembly, alone, which every script sees.
    [Generator]
    public sealed class SchemaGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context)
        {
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (context.Compilation.AssemblyName != "Tide.Game") return;
            var path = FindSchema(context.Compilation, context.AdditionalFiles);
            string text = null;
            try
            {
                if (path != null) text = File.ReadAllText(path);
            }
            catch (IOException)
            {
                // tide is writing it: the next compile reads it
            }
            if (text == null)
            {
                context.ReportDiagnostic(Diagnostic.Create(new DiagnosticDescriptor("TIDE001", "No Tide schema",
                    "No Library/Tide/schema.json from {0}: the game's types are generated once tide unity has built it",
                    "Tide", DiagnosticSeverity.Warning, true), Location.None, Directory.GetCurrentDirectory()));
            }
            context.AddSource("TideGame.g.cs", SourceText.From(Emit(text), Encoding.UTF8));
        }

        // The project's Library/Tide/schema.json: in the project Unity's UnityAdditionalFile.txt names (which it gives
        // each assembly it compiles), else from the folder Unity compiles in, or above a source of the assembly.
        static string FindSchema(Compilation compilation, IEnumerable<AdditionalText> additional)
        {
            var candidates = new List<string>();
            foreach (var file in additional)
            {
                // The package's csc.rsp hands it over, so it's an input of the compile Unity's build cache knows
                if (Path.GetFileName(file.Path) == "schema.json" && File.Exists(file.Path)) return file.Path;
            }
            foreach (var file in additional)
            {
                if (!file.Path.EndsWith("UnityAdditionalFile.txt", StringComparison.OrdinalIgnoreCase)) continue;
                var project = file.GetText()?.ToString().Trim();
                if (string.IsNullOrEmpty(project)) continue;
                // The embedded package tide unity writes, whose stub makes Unity compile again for a new schema;
                // else the build's own
                var schema = Path.Combine(project, "Packages", "com.tide.game", "schema.json");
                if (File.Exists(schema)) return schema;
                schema = Path.Combine(project, "Library", "Tide", "schema.json");
                if (File.Exists(schema)) return schema;
            }
            candidates.Add(Directory.GetCurrentDirectory());
            foreach (var tree in compilation.SyntaxTrees)
            {
                if (!string.IsNullOrEmpty(tree.FilePath) && Path.IsPathRooted(tree.FilePath)) candidates.Add(Path.GetDirectoryName(tree.FilePath));
            }
            foreach (var start in candidates)
            {
                for (var dir = start; !string.IsNullOrEmpty(dir); dir = Path.GetDirectoryName(dir))
                {
                    var schema = Path.Combine(dir, "Library", "Tide", "schema.json");
                    if (File.Exists(schema)) return schema;
                }
            }
            return null;
        }

        sealed class TypeInfo
        {
            public string Name, Kind, CsName, Namespace;
            public bool Local;
            public uint Size;
            public List<Dictionary<string, object>> Fields;
        }

        static string Emit(string text)
        {
            var o = new StringBuilder();
            o.AppendLine("// Generated by Tide's package from Library/Tide/schema.json. Do not edit: it changes with the game.");
            o.AppendLine("#pragma warning disable");
            var schema = text != null ? Json.Parse(text) as Dictionary<string, object> : null;
            if (schema == null)
            {
                o.AppendLine("namespace Tide.Game { public static class TideGameSchema { public const string Hash = \"\"; } }");
                return o.ToString();
            }
            var types = List(schema, "types").Select(t => t as Dictionary<string, object>).ToList();
            var enums = List(schema, "enums").Select(e => e as Dictionary<string, object>).ToList();
            var infos = new List<TypeInfo>();
            var taken = new HashSet<string>();
            foreach (var t in types)
            {
                var name = Str(t, "name");
                var kind = Str(t, "kind");
                var local = kind == "local";
                var bare = local && name.EndsWith(" local") ? name.Substring(0, name.Length - " local".Length) : name;
                var dot = bare.LastIndexOf('.');
                var ns = dot > 0 ? string.Join(".", bare.Substring(0, dot).Split('.').Select(Identifier)) : null;
                var cs = Identifier(dot > 0 ? bare.Substring(dot + 1) : bare) + (local ? "Local" : "");
                var full = (ns != null ? ns + "." : "") + cs;
                while (!taken.Add(full))
                {
                    cs += "_";
                    full = (ns != null ? ns + "." : "") + cs;
                }
                infos.Add(new TypeInfo
                {
                    Name = local ? bare : name, Kind = kind, CsName = cs, Namespace = ns, Local = local,
                    Size = (uint)Num(t, "size"), Fields = List(t, "fields").Select(f => f as Dictionary<string, object>).ToList(),
                });
            }
            var enumNames = new List<string>();
            foreach (var e in enums)
            {
                var name = Str(e, "name");
                var dot = name.LastIndexOf('.');
                enumNames.Add("global::Tide.Game." + (dot > 0 ? string.Join(".", name.Substring(0, dot).Split('.').Select(Identifier)) + "." : "")
                              + Identifier(dot > 0 ? name.Substring(dot + 1) : name));
            }

            o.AppendLine("namespace Tide.Game");
            o.AppendLine("{");
            o.AppendLine("    // What this game's bindings were made from: a view packet of another build isn't read by them.");
            o.AppendLine("    public static class TideGameSchema");
            o.AppendLine("    {");
            o.AppendLine($"        public const string Hash = \"{Escape(Str(schema, "hash"))}\";");
            o.AppendLine($"        public const string Game = \"{Escape(Str(schema, "game"))}\";");
            o.AppendLine($"        public const int TickRate = {(int)Num(schema, "tickRate")};");
            var scenes = List(schema, "scenes").Select(s => s as string).ToList();
            o.AppendLine("        public static readonly string[] Scenes = { " + string.Join(", ", scenes.Select(s => "\"" + Escape(s) + "\"")) + " };");
            var prefabs = List(schema, "prefabs").Select(s => s as string).ToList();
            o.AppendLine("        public static readonly string[] Prefabs = { " + string.Join(", ", prefabs.Select(s => "\"" + Escape(s) + "\"")) + " };");
            o.AppendLine("    }");
            o.AppendLine("}");

            for (var i = 0; i < enums.Count; i++)
            {
                var e = enums[i];
                var name = Str(e, "name");
                var dot = name.LastIndexOf('.');
                OpenNamespace(o, dot > 0 ? string.Join(".", name.Substring(0, dot).Split('.').Select(Identifier)) : null);
                o.AppendLine($"    public enum {Identifier(dot > 0 ? name.Substring(dot + 1) : name)} : int");
                o.AppendLine("    {");
                var members = List(e, "members");
                var values = List(e, "values");
                var used = new HashSet<string>();
                for (var k = 0; k < members.Count; k++)
                {
                    var member = Identifier(members[k] as string);
                    if (!used.Add(member)) continue;
                    o.AppendLine($"        {member} = {(k < values.Count ? (int)(double)values[k] : k)},");
                }
                o.AppendLine("    }");
                o.AppendLine("}");
            }

            foreach (var info in infos)
            {
                OpenNamespace(o, info.Namespace);
                o.AppendLine($"    // Tide's {info.Kind} {info.Name}{(info.Local ? "'s local fields" : "")}");
                o.AppendLine($"    [global::Tide.TideType(\"{Escape(info.Name)}\"{(info.Local ? ", true" : "")})]");
                o.AppendLine($"    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Explicit, Size = {Math.Max(1u, info.Size)})]");
                o.AppendLine($"    public unsafe partial struct {info.CsName}");
                o.AppendLine("    {");
                var names = new HashSet<string> { info.CsName };
                foreach (var f in info.Fields)
                {
                    var fieldName = Identifier(Str(f, "name"));
                    while (!names.Add(fieldName)) fieldName += "_";
                    var offset = (uint)Num(f, "offset");
                    var size = (uint)Num(f, "size");
                    var cs = FieldType(f, infos, enumNames);
                    if (cs == null)
                    {
                        if (size == 0) continue;
                        o.AppendLine($"        [global::System.Runtime.InteropServices.FieldOffset({offset})] public fixed byte {fieldName}[{size}]; // {Escape(Str(f, "type"))}: its bytes");
                    }
                    else
                    {
                        o.AppendLine($"        [global::System.Runtime.InteropServices.FieldOffset({offset})] public {cs} {fieldName};");
                    }
                }
                o.AppendLine("    }");
                o.AppendLine("}");
            }
            return o.ToString();
        }

        // The C# type a field reads as, or null for its bytes alone.
        static string FieldType(Dictionary<string, object> f, List<TypeInfo> infos, List<string> enumNames)
        {
            var type = Str(f, "type");
            var kind = Str(f, "kind");
            var size = (uint)Num(f, "size");
            var reference = (int)Num(f, "ref", -1);
            switch (kind)
            {
                case "text": return "global::Tide.TideText";
                case "list": return "global::Tide.TideList";
                case "entity": return "global::Tide.TideEntityId";
                case "map":
                case "grid": return null;
                case "struct":
                    if (reference >= 0 && reference < infos.Count)
                    {
                        var t = infos[reference];
                        if (t.Size == size) return "global::Tide.Game." + (t.Namespace != null ? t.Namespace + "." : "") + t.CsName;
                    }
                    break;
                case "enum":
                    if (reference >= 0 && reference < enumNames.Count && size == 4) return enumNames[reference];
                    break;
            }
            switch (type)
            {
                case "bool": return size == 1 ? "bool" : null;
                case "byte": return size == 1 ? "byte" : null;
                case "int": return size == 4 ? "int" : null;
                case "char": return size == 4 ? "int" : null;
                case "long": return size == 8 ? "long" : null;
                case "float": return size == 4 ? "float" : null;
                case "double": return size == 8 ? "double" : null;
                case "PlayerID": return size == 4 ? "uint" : null;
                case "float2": return size == 8 ? "global::UnityEngine.Vector2" : null;
                case "float3": return size == 12 ? "global::UnityEngine.Vector3" : null;
                case "float4": return size == 16 ? "global::UnityEngine.Vector4" : null;
                case "int2": return size == 8 ? "global::UnityEngine.Vector2Int" : null;
                case "int3": return size == 12 ? "global::UnityEngine.Vector3Int" : null;
                case "quaternion": return size == 16 ? "global::UnityEngine.Quaternion" : null;
                case "Color": return size == 16 ? "global::UnityEngine.Color" : null;
                case "Rect": return size == 16 ? "global::UnityEngine.Rect" : null;
                case "float4x4": return size == 64 ? "global::UnityEngine.Matrix4x4" : null;
            }
            return null;
        }

        static void OpenNamespace(StringBuilder o, string ns)
        {
            o.AppendLine(ns != null ? $"namespace Tide.Game.{ns}" : "namespace Tide.Game");
            o.AppendLine("{");
        }

        // A name C# takes: what an identifier can't hold as _, a keyword with @.
        static string Identifier(string name)
        {
            if (string.IsNullOrEmpty(name)) return "_";
            var b = new StringBuilder();
            foreach (var c in name)
            {
                if (c == '?') b.Append("Optional");
                else b.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            }
            var s = b.ToString();
            if (char.IsDigit(s[0])) s = "_" + s;
            return SyntaxFacts.GetKeywordKind(s) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(s) == SyntaxKind.VarKeyword ? "@" + s : s;
        }

        static string Escape(string s)
        {
            return (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        static List<object> List(Dictionary<string, object> o, string key)
        {
            return o != null && o.TryGetValue(key, out var v) && v is List<object> l ? l : new List<object>();
        }

        static string Str(Dictionary<string, object> o, string key)
        {
            return o != null && o.TryGetValue(key, out var v) && v is string s ? s : "";
        }

        static double Num(Dictionary<string, object> o, string key, double otherwise = 0)
        {
            return o != null && o.TryGetValue(key, out var v) && v is double d ? d : otherwise;
        }
    }
}
